const std = @import("std");

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});

    const module = b.addModule("zizek", .{
        .root_source_file = b.path("zizek.zig"),
        .target = target,
        .optimize = optimize,
    });
    // The conformance tables live outside the package, so only the test build
    // of the same root embeds them. The public module stays self-contained:
    // a dependent build, or a standalone release checkout, never resolves
    // these paths.
    const test_module = b.createModule(.{
        .root_source_file = b.path("zizek.zig"),
        .target = target,
        .optimize = optimize,
    });
    // The shell-level conformance table, shared with the other packages.
    test_module.addAnonymousImport("shell_cases", .{
        .root_source_file = b.path("../../conformance/shell/shell_cases.tsv"),
    });
    // Generated by tools/tracegen from the real Hegel engine, and embedded
    // separately rather than merged into the hand-written table so that it
    // stays regenerable.
    test_module.addAnonymousImport("trace_vectors", .{
        .root_source_file = b.path("../../conformance/shell/trace_vectors.tsv"),
    });
    test_module.addAnonymousImport("database_cases", .{
        .root_source_file = b.path("../../conformance/database/database_cases.tsv"),
    });
    // The generated readers for those tables are test-only modules too, so
    // they stay out of the published package.
    for ([_][]const u8{ "drawops_gen_test", "shellcases_gen_test", "databasecases_gen_test" }) |reader| {
        test_module.addAnonymousImport(reader, .{
            .root_source_file = b.path(b.fmt("{s}.zig", .{reader})),
        });
    }
    const tests = b.addTest(.{ .root_module = test_module });
    const run_tests = b.addRunArtifact(tests);
    // `zig build test -Dverbose-tests` hands the runner the terminal, so it
    // prints each test's name instead of reporting only to the build summary.
    if (b.option(bool, "verbose-tests", "Print each test's name as it runs") orelse false) {
        run_tests.stdio = .inherit;
    }
    const test_step = b.step("test", "Run the Zig package tests");
    test_step.dependOn(&run_tests.step);

    const ledger_module = b.createModule(.{
        .root_source_file = b.path("examples/ledger.zig"),
        .target = target,
        .optimize = optimize,
    });
    ledger_module.addImport("zizek", module);
    const ledger = b.addExecutable(.{
        .name = "zizek-ledger",
        .root_module = ledger_module,
    });
    b.installArtifact(ledger);
    const ledger_tests = b.addTest(.{ .root_module = ledger_module });
    const run_ledger_tests = b.addRunArtifact(ledger_tests);
    test_step.dependOn(&run_ledger_tests.step);

    const die_hard_module = b.createModule(.{
        .root_source_file = b.path("examples/die_hard.zig"),
        .target = target,
        .optimize = optimize,
    });
    die_hard_module.addImport("zizek", module);
    const die_hard = b.addExecutable(.{
        .name = "zizek-die-hard",
        .root_module = die_hard_module,
    });
    b.installArtifact(die_hard);
    const die_hard_tests = b.addTest(.{ .root_module = die_hard_module });
    const run_die_hard_tests = b.addRunArtifact(die_hard_tests);
    test_step.dependOn(&run_die_hard_tests.step);

    const run_die_hard = b.addRunArtifact(die_hard);
    const run_die_hard_step = b.step("run-die-hard", "Run the Die Hard state-machine example");
    run_die_hard_step.dependOn(&run_die_hard.step);

    const upstream_examples = [_]struct {
        name: []const u8,
        source: []const u8,
        description: []const u8,
    }{
        .{
            .name = "hypothesis-quickstart",
            .source = "examples/hypothesis_quickstart.zig",
            .description = "Run the Hypothesis quickstart port",
        },
        .{
            .name = "min-stack",
            .source = "examples/min_stack.zig",
            .description = "Run the Hegel minimum-stack port",
        },
        .{
            .name = "stack",
            .source = "examples/stack.zig",
            .description = "Run the Hegel stack-model port",
        },
        .{
            .name = "multi",
            .source = "examples/multi.zig",
            .description = "Run the Hegel multiple-origin port",
        },
    };
    for (upstream_examples) |example| {
        const example_module = b.createModule(.{
            .root_source_file = b.path(example.source),
            .target = target,
            .optimize = optimize,
        });
        example_module.addImport("zizek", module);
        const executable = b.addExecutable(.{
            .name = b.fmt("zizek-{s}", .{example.name}),
            .root_module = example_module,
        });
        b.installArtifact(executable);

        const example_tests = b.addTest(.{ .root_module = example_module });
        const run_example_tests = b.addRunArtifact(example_tests);
        test_step.dependOn(&run_example_tests.step);

        const run_example = b.addRunArtifact(executable);
        const run_step = b.step(b.fmt("run-{s}", .{example.name}), example.description);
        run_step.dependOn(&run_example.step);
    }
}
